#include <unistd.h>

int main(void)
{
    int i = 122;
    while (i >= 97)
    {
        if (i % 2 == 1)
        {
            i = i - 32;
            write(1, &i, 1);
            i = i + 32;
        }
        write(1, &i, 1);
        i--;
    }
    write(1, "\n", 1);
    return(0);
}