#include <unistd.h>

void maff_alpha(void)
{
    int i = 97;
    while (i <= 122)
    {
        if (i % 2 == 0)
        {
            i = i - 32;
            write(1, &i, 1);
            i = i + 32;
        }
        else
            write(1, &i, 1);
        i++;
    }
    write(1, "\n", 1);
}

int main(void)
{
    maff_alpha();
}